/**
 * Questionnaire — shadcn/ui `questionnaire`, vendored from the `base-vega` style (HOW-27).
 * Provenance: `npx shadcn@latest add questionnaire`, kept VERBATIM — the only edit is this
 * header. The `cn-*` class names and the `IconPlaceholder` import in the registry's GitHub
 * source are pre-substitution template artefacts; what `shadcn add` actually writes, and what
 * is below, is plain Tailwind against the standard colour contract that globals.css already
 * maps onto howdah's tokens.
 *
 * It rides on `@shadcn/react` (20KB, zero runtime dependencies, `react` its only peer) and
 * imports nothing from `@base-ui/react`, so `No Radix, ever` is satisfied rather than bent —
 * the `base`, `radix` and `aria` flavours of this file are byte-identical apart from the button
 * import, which is what proves the primitive underneath is not a primitives library.
 *
 * Why it is here rather than hand-rolled onto the existing `AskQuestionCard` (HOW-25): a
 * harness's `AskUserQuestion` is asked ONE QUESTION AT A TIME in the CLIs this viewer is
 * judged against, with the options numbered and Enter to advance. That is a small state
 * machine — ordered items, an active item, per-item answered/skipped status, required-ness,
 * validation, letter/number shortcuts bound without stealing keys from a text field, and
 * `aria-keyshortcuts` on the right elements — and it is the part that is tedious to own and
 * invisible when wrong. The MEANING of an answer stays in `core/ask.ts`, which is unchanged.
 *
 * One integration fact that is NOT obvious from the docs, and that decided how `run/ask.tsx`
 * reads this: `QuestionnaireInput` joins the form under the ITEM's own field name — the same
 * name the choices carry — as soon as it becomes that item's selected answer. Until then it is
 * detached (`name: selectedAnswerIds.includes(ownId) ? item.name : undefined`, with `form=""`
 * while it is not), which is why an untouched card shows no name on it. So the moment the
 * operator types "something else", `new FormData(form).getAll(id)` returns chosen labels and
 * typed text indistinguishably — and `validateAnswers` REFUSES a `selected` value that is not
 * one of the question's own option labels. Reading the form would turn a free-text answer into
 * a 400 exactly when it was used. The answer state is therefore held controlled by the caller
 * (`checked` + `onChange`), and `FormData` is never read. Explicit over clever, and it leaves
 * the free-text field able to contain anything, including something that happens to read like
 * an option label.
 *
 * `cn` comes from the `cn` package, not `@/lib/utils`, because that is what base-vega ships and
 * "a component pulled with `shadcn add` compiles unedited" is the contract `lib/utils.ts`
 * exists to keep. See message-scroller.tsx's header on the two merge helpers.
 */
