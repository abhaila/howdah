/**
 * The gate that would have caught BOTH HOW-16 P0 defects before they shipped.
 *
 * `.tab.on` was emitted by a component while the stylesheet defined `.tab.active`; `.chip`
 * and `.pill` had modifiers but no base rule at all. Nothing could catch either: TypeScript
 * does not read CSS, the bundler does not read `className`, and a missing rule renders as
 * "plain text", which looks like a design choice rather than a bug. So the contract between
 * the two layers is checked here, in both directions:
 *
 *   1. every class a .tsx emits has a rule somewhere, and
 *   2. every rule a stylesheet defines has a consumer.
 *
 * Direction 2 is what keeps the sweep from growing a new pile of dead CSS the moment this
 * lands — it is the check that found the twelve classes HOW-16 deleted.
 *
 * Two things this deliberately does NOT do. It does not parse CSS or TSX properly: a regex
 * over both is enough to catch a name that exists on one side and not the other, and a real
 * parser would be a dependency and a maintenance burden for a check that only needs names.
 * And it does not see Tailwind utilities — those are generated by Tailwind from the same
 * source it scans, so a typo there produces no class rather than a dangling one, and the
 * component tests are what pin the ones that carry meaning.
 */
import { beforeAll, describe, expect, test } from "bun:test";
import { mkdtempSync, readdirSync, readFileSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const APP = new URL(".", import.meta.url).pathname.replace(/\/$/, "");
const REPO = join(APP, "..", "..");
const SHEETS = [
  join(REPO, "web/public/tokens.css"),
  join(REPO, "web/public/howdah.css"),
  join(REPO, "web/app/globals.css"),
];

function walk(dir: string, out: string[] = []): string[] {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.tsx$/.test(p) && !/\.test\.tsx$/.test(p)) out.push(p);
  }
  return out;
}
const SOURCES = walk(APP).sort();

/**
 * Names composed at runtime from data — `depth-${r.depth}`, `scope-${e.scope}`,
 * `kind-${n.kind}`, `pr-${state}`. A scan cannot see the value, so each prefix is declared
 * ONCE here, with what feeds it, and a rule under that prefix counts as consumed. This list
 * is the only place a class may be exempt, and adding to it is a deliberate act.
 */
const COMPOSED_PREFIXES: Array<{ prefix: string; fedBy: string }> = [
  { prefix: "depth-", fedBy: "run/logs.tsx: `log-row ${r.kind} depth-${r.depth}`" },
  { prefix: "kind-", fedBy: "graph-dag.tsx `dag-node … kind-${n.kind}`, builder/node-card.tsx `gb-node kind-${kind}`" },
];

/**
 * Names a component picks at runtime through a VARIABLE rather than an interpolation — the
 * scan sees `${cls}`, not the four values it can hold. Each is named with the site that
 * chooses it, so an orphan rule still has to be explained rather than assumed.
 */
/**
 * Container classes that carry no styling of their own and exist as a STRUCTURE hook — a
 * wrapper a descendant rule reaches through, or a grouping the markup needs anyway. They are
 * listed rather than given empty rules, because an empty rule is a worse lie than a list.
 */
const STRUCTURAL: string[] = [
  "dag",            // the <svg> itself; every rule targets what is inside it
  "ap-traces", "ap-rounds", "ghost-item", "map-pane",  // slice.tsx grouping wrappers
  "dv-group", "dv-reason",                             // drift grouping + its prose line
  "gr-prose",                                          // inherits .gr-sub entirely
  "sd-rowless-ask",                                    // the panel-carried ask; has a testid
];

/**
 * Names a LIBRARY reads, not a stylesheet (HOW-24). React Flow's `nodrag` / `nopan` are its
 * documented interaction opt-outs: it queries for them in JavaScript to decide whether a
 * pointer press starts a node drag or a canvas pan. They are behaviour, and the vendor sheet
 * deliberately gives them no rules — so direction 1 would call them dangling and an empty rule
 * would be a lie about what they do. Listing them is the honest version, and it is the only
 * reason a class may be exempt without a rule anywhere.
 */
const BEHAVIOURAL: Array<{ name: string; readBy: string }> = [
  { name: "nodrag", readBy: "@xyflow/react — a press here must not drag the step's card" },
  { name: "nopan", readBy: "@xyflow/react — a press here must not pan the canvas" },
];

const COMPOSED_NAMES: Array<{ name: string; fedBy: string }> = [
  { name: "meta", fedBy: "screens/prompts.tsx Diff: `dl ${cls}`" },
  { name: "hunk", fedBy: "screens/prompts.tsx Diff: `dl ${cls}`" },
  { name: "add", fedBy: "screens/prompts.tsx Diff: `dl ${cls}`" },
  { name: "del", fedBy: "screens/prompts.tsx Diff: `dl ${cls}`" },
  { name: "ctx", fedBy: "screens/prompts.tsx Diff: `dl ${cls}`" },
  // `model`, `tool`, `operator` and `error` were fed by run/view.tsx's TranscriptRow, which
  // went with the Thread tab. Their rules went too, so the exemptions go — which is exactly
  // what the "allowlist stays honest" test below demands, and why it exists.
  { name: "attention", fedBy: "run/logs.tsx: `log-row ${r.kind}` — deriveLogRows' kind" },
];

/** Element/pseudo/at-rule noise a class regex must not mistake for a class name. */
const RULE_RE = /\.(-?[A-Za-z_][\w-]*)/g;

/**
 * Class names a .tsx emits. Only `className=` is read, and its `{…}` form is BRACE-MATCHED
 * rather than regexed to the first `}` — a template like
 * `` `log-row ${r.kind} depth-${r.depth}` `` contains braces, and stopping at the first one
 * silently loses every class after it. (That is how a scan quietly reports classes as dead.)
 */
export function classesUsedIn(src: string): Set<string> {
  const out = new Set<string>();
  const add = (chunk: string) => {
    for (const w of chunk.split(/\s+/)) if (/^[A-Za-z][\w-]*$/.test(w)) out.add(w);
  };
  for (const m of src.matchAll(/className\s*=\s*"([^"]*)"/g)) add(m[1]!);
  for (const m of src.matchAll(/className\s*=\s*\{/g)) {
    const start = m.index! + m[0]!.length;
    // blanked at the top level too: `className={x === "ok" ? "a" : "b"}` is not inside a
    // template, and its comparand is no more a class name there than inside one
    for (const lit of literals(blankComparands(src.slice(start, matchingBrace(src, start))))) add(lit);
  }
  return out;
}

/**
 * Inside a hole, a literal after a comparison is a VALUE being tested, not a class:
 * `${state === "delivered" ? "collapsing" : ""}` emits `collapsing`, never `delivered`.
 * Without this the scan demands a `.delivered` rule and the gate cries wolf.
 */
const blankComparands = (expr: string) => expr.replace(/(===|!==|==|!=)\s*(["'`])[^"'`]*\2/g, "$1 0");

/** Index of the `}` that closes a `{` already consumed at `from`. */
function matchingBrace(src: string, from: number): number {
  let depth = 1;
  let i = from;
  while (i < src.length && depth > 0) {
    if (src[i] === "{") depth++;
    else if (src[i] === "}") depth--;
    i++;
  }
  return i - 1;
}

/**
 * Every string-literal chunk in a `className={…}` expression, descending into template
 * holes so `${cond ? "active" : ""}` yields `active`, and leaving a SPACE where the hole was
 * so `depth-${n}` yields the prefix `depth-` rather than `depth-n`.
 *
 * A real scan, not a regex pair-up: pairing quotes alternately gets `` `nav ${x ? "a" : ""}` ``
 * wrong — it reads the quote AFTER `a` as the next opening one and drops `a` entirely. That
 * is the failure mode that makes a scanner call live classes dead, and it is exactly the kind
 * of quiet wrongness this whole file exists to prevent, so it is worth the twenty lines.
 * Bare identifiers are never collected, which is what lets both directions be strict.
 */
function literals(expr: string, out: string[] = []): string[] {
  let i = 0;
  while (i < expr.length) {
    const q = expr[i];
    if (q !== '"' && q !== "'" && q !== "`") { i++; continue; }
    i++;
    let buf = "";
    while (i < expr.length && expr[i] !== q) {
      if (expr[i] === "\\") { i += 2; continue; }
      if (q === "`" && expr[i] === "$" && expr[i + 1] === "{") {
        const start = i + 2;
        i = matchingBrace(expr, start) + 1;
        literals(blankComparands(expr.slice(start, i - 1)), out);
        buf += " ";
        continue;
      }
      buf += expr[i++];
    }
    i++;
    out.push(buf);
  }
  return out;
}

/** Class names a stylesheet defines. */
function classesDefinedIn(css: string): Set<string> {
  // strip declaration blocks and comments, so `color: var(--x)` and prose cannot look like rules
  const selectorsOnly = css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\{[^{}]*\}/g, "{}");
  const out = new Set<string>();
  for (const m of selectorsOnly.matchAll(RULE_RE)) out.add(m[1]!);
  return out;
}

/** Comments are stripped first: several component headers QUOTE the markup they replaced
 *  (`<span className={`pill scope-${e.scope}`}>`), and a scan that reads those reports the
 *  very classes this sweep deleted as still in use. */
const decomment = (src: string) => src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");

const USED = new Set<string>();
for (const f of SOURCES) for (const c of classesUsedIn(decomment(readFileSync(f, "utf8")))) USED.add(c);
const DEFINED = new Map<string, string>();
for (const f of SHEETS) for (const c of classesDefinedIn(readFileSync(f, "utf8"))) if (!DEFINED.has(c)) DEFINED.set(c, f);

const composed = (c: string) =>
  COMPOSED_PREFIXES.some(({ prefix }) => c === prefix || c.startsWith(prefix)) ||
  COMPOSED_NAMES.some(({ name }) => name === c);
const exempt = (c: string) => composed(c) || STRUCTURAL.includes(c) || BEHAVIOURAL.some((b) => b.name === c);

/**
 * Direction 1 needs Tailwind's OUTPUT, not its input: most classes the components emit are
 * utilities Tailwind generates from these same sources, and a hand-written name like `on` is
 * exactly the one it will not generate. So the app is bundled into a temp dir with the same
 * plugin `bun run web` uses, and the emitted names are checked against everything that
 * actually ships: the generated utilities plus the three hand-written sheets.
 */
let SHIPPED: Set<string> | null = null;
beforeAll(async () => {
  const tailwind = (await import("bun-plugin-tailwind")).default;
  const outdir = mkdtempSync(join(tmpdir(), "howdah-css-"));
  const result = await Bun.build({
    entrypoints: [join(APP, "main.tsx")],
    outdir,
    naming: "app.[ext]",
    plugins: [tailwind],
    minify: false,
  });
  if (!result.success) throw new Error("app bundle failed: " + result.logs.join("\n"));
  SHIPPED = new Set(DEFINED.keys());
  for (const c of classesDefinedIn(readFileSync(join(outdir, "app.css"), "utf8"))) SHIPPED.add(c);
});

describe("the CSS contract between the component layer and the stylesheets", () => {
  test("every class a component emits has a rule that ships (P0 defect 1's gate)", () => {
    // `.tab.on` was emitted here and defined NOWHERE; this is the assertion that says so
    const dangling = [...USED].filter((c) => !SHIPPED!.has(c) && !exempt(c)).sort();
    expect(dangling).toEqual([]);
  });

  test("every rule a stylesheet defines has a consumer (no dead CSS)", () => {
    const orphans = [...DEFINED.keys()].filter((c) => !USED.has(c) && !composed(c)).sort();
    expect(orphans).toEqual([]);
  });

  test("the twelve classes HOW-16 deleted are gone, and stay gone", () => {
    const deleted = [
      "ide-btn", "theme-toggle", "form-card", "tuner-card", "model-chip", "ws-kind",
      "ws-remove", "tool-cluster", "tool-detail", "ask-reason", "pr-state",
    ];
    expect(deleted.filter((c) => DEFINED.has(c))).toEqual([]);
  });

  test("the allowlist stays honest: every exemption still has a rule to exempt", () => {
    for (const { prefix, fedBy } of COMPOSED_PREFIXES) {
      const rules = [...DEFINED.keys()].filter((c) => c.startsWith(prefix) && c !== prefix);
      expect(rules.length, `no rule under "${prefix}" (${fedBy}) — drop it from the allowlist`).toBeGreaterThan(0);
    }
    for (const { name, fedBy } of COMPOSED_NAMES) {
      expect(DEFINED.has(name), `"${name}" (${fedBy}) has no rule — drop it from the allowlist`).toBe(true);
    }
  });
});

describe("tokens.css is the single source of colour and type (P3.12)", () => {
  const OTHERS = SHEETS.filter((f) => !f.endsWith("tokens.css"));

  test("no hex outside tokens.css", () => {
    for (const f of OTHERS) {
      const hex = readFileSync(f, "utf8")
        .split("\n")
        .map((line, i) => ({ line, i }))
        .filter(({ line }) => /#[0-9a-fA-F]{3,8}\b/.test(line) && !/brand/i.test(line));
      expect(hex.map(({ line, i }) => `${f}:${i + 1} ${line.trim()}`)).toEqual([]);
    }
  });

  test("no `font-size: Npx` outside tokens.css — the ladder is a token", () => {
    for (const f of OTHERS) {
      const px = readFileSync(f, "utf8").match(/font-size:\s*[\d.]+px/g) ?? [];
      expect(px, `${f} still hardcodes a font size`).toEqual([]);
    }
  });

  test("tokens.css defines the whole type scale the two systems share", () => {
    const tokens = readFileSync(SHEETS[0]!, "utf8");
    for (const step of ["3xs", "2xs", "xs", "code", "sm", "base", "body", "md", "lg", "xl"]) {
      expect(tokens, `--type-${step} is missing`).toContain(`--type-${step}:`);
    }
    // and globals.css re-exports them, or `text-base` and var(--type-base) can drift apart
    const globals = readFileSync(SHEETS[2]!, "utf8");
    for (const step of ["xs", "sm", "base", "md", "lg"]) {
      expect(globals).toContain(`--text-${step}: var(--type-${step})`);
    }
  });

  test("the only hex left in the TypeScript layer is the brand mark's, and it says so", () => {
    for (const f of SOURCES) {
      const lines = readFileSync(f, "utf8").split("\n");
      const bad = lines
        .map((line, i) => ({ line, i }))
        .filter(({ line }) => /#[0-9a-fA-F]{6}\b/.test(line))
        // allowed only where a comment within two lines says WHY it is not a token
        .filter(({ i }) => !lines.slice(Math.max(0, i - 3), i + 2).some((l) => /brand/i.test(l)))
        .map(({ line, i }) => `${f}:${i + 1} ${line.trim()}`);
      expect(bad).toEqual([]);
    }
  });
});

